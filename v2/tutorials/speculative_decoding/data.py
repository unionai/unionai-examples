"""Build the draft model's training data from the target model's own outputs.

A draft head learns to predict what the *target* would say next, so its training data
must be target-generated. Two sources feed it:

- General chat: UltraChat prompts, with responses regenerated by Qwen3-8B.
- Agent traces: ToolACE tool-calling episodes, run end to end against Qwen3-8B.

Both are fanned out over shards. Each shard runs on a reusable GPU container that keeps
one vLLM server warm, so only the first shard on a replica pays for the model load. Every
task renders a report: what was sampled, what each shard generated, and the final mix.
"""

import asyncio
import json
import subprocess
from dataclasses import dataclass, field

import flyte
from flyte.io import File

import data_reports
from config import TARGET_MODEL, data_env, driver_env, generate_env
from vllm_server import TOOL_ARGS, VLLMServer, start_server
from workloads import NO_THINKING, http_complete, load_agent_tasks, load_chat_prompts, run_agent


@dataclass
class PromptShards:
    chat: list[File]
    agent: list[File]


# {{docs-fragment shard}}
@dataclass
class Shard:
    """One shard of generated training data and what is in it."""

    data: File
    kind: str  # "chat" or "agent"
    rows: int = 0
    tokens: int = 0  # Tokens the trainer sees, prompt included.
    target_tokens: int = 0  # Tokens written by the target model: what the draft learns.
    tool_calls: int = 0
    failed: int = 0
    lengths: list[int] = field(default_factory=list)  # Target tokens per row.


@dataclass
class TrainingData:
    chat: list[Shard]
    agent: list[Shard]

    @property
    def files(self) -> list[File]:
        return [s.data for s in self.chat + self.agent]
# {{/docs-fragment shard}}


# {{docs-fragment prepare-prompts}}
@data_env.task(cache="auto", report=True)
async def prepare_prompts(num_chat: int, num_agent: int, num_shards: int) -> PromptShards:
    """Sample prompts and split them into shards for parallel generation."""

    async def write_shards(rows: list[dict], prefix: str) -> list[File]:
        files = []
        for i in range(num_shards):
            path = f"/tmp/{prefix}-{i}.jsonl"
            with open(path, "w") as f:
                for row in rows[i::num_shards]:
                    f.write(json.dumps(row) + "\n")
            files.append(await File.from_local(path))
        return files

    chat = [{"messages": m} for m in load_chat_prompts(num_chat)]
    agent = load_agent_tasks("train", num_agent)
    await flyte.report.replace.aio(data_reports.prompts_report(chat, agent, num_shards))
    await flyte.report.flush.aio()
    return PromptShards(
        chat=await write_shards(chat, "chat"),
        agent=await write_shards(agent, "agent"),
    )
# {{/docs-fragment prepare-prompts}}


# One server per reusable container, started by the first task that lands on it.
_server: VLLMServer | None = None


def _get_server() -> VLLMServer:
    global _server
    if _server is None or _server.process.poll() is not None:
        _server = start_server(
            extra_args=[*TOOL_ARGS, "--max-model-len", "8192", "--gpu-memory-utilization", "0.9"]
        )
    return _server


# {{docs-fragment regenerate}}
@generate_env.task(cache="auto", report=True)
async def regenerate_chat(shard: File) -> Shard:
    """Replace the dataset's responses with Qwen3-8B's own, tokenized for training."""
    server = _get_server()
    local = await shard.download()
    out = "/tmp/regenerated.jsonl"
    subprocess.run(
        [
            "speculators", "regenerate-responses",
            "--endpoint", f"{server.base_url}/v1/chat/completions",
            "--dataset", local,
            "--outfile", out,
            "--max-tokens", "2048",
            "--concurrency", "64",
            "--sampling-params", json.dumps({"temperature": 0.7, **NO_THINKING}),
        ],
        check=True,
    )
    with open(out) as f:
        rows = [json.loads(line) for line in f]
    with open(local) as f:
        requested = sum(1 for _ in f)

    lengths = [sum(r["loss_mask"]) for r in rows]
    result = Shard(
        data=await File.from_local(out),
        kind="chat",
        rows=len(rows),
        tokens=sum(len(r["input_ids"]) for r in rows),
        target_tokens=sum(lengths),
        failed=max(requested - len({r.get("primary_id") for r in rows}), 0),
        lengths=lengths,
    )
    await flyte.report.replace.aio(data_reports.chat_shard_report(result, rows))
    await flyte.report.flush.aio()
    return result
# {{/docs-fragment regenerate}}


# {{docs-fragment agent-traces}}
@generate_env.task(cache="auto", report=True)
async def collect_agent_traces(shard: File, concurrency: int = 32) -> Shard:
    """Run each agent task against Qwen3-8B and record the full episode."""
    import httpx
    from transformers import AutoTokenizer

    server = _get_server()
    with open(await shard.download()) as f:
        tasks = [json.loads(line) for line in f]

    semaphore = asyncio.Semaphore(concurrency)
    async with httpx.AsyncClient() as client:
        complete = http_complete(client, server.base_url)

        async def one(task: dict) -> dict | None:
            async with semaphore:
                try:
                    return await run_agent(complete, task)
                except Exception as e:  # A malformed tool schema should not sink the shard.
                    print(f"agent episode failed: {e}")
                    return None

        traces = [t for t in await asyncio.gather(*(one(t) for t in tasks)) if t]

    out = "/tmp/agent-traces.jsonl"
    with open(out, "w") as f:
        for trace in traces:
            f.write(json.dumps(trace) + "\n")

    tokenizer = AutoTokenizer.from_pretrained(TARGET_MODEL)
    stats = [data_reports.trace_stats(t, tokenizer) for t in traces]
    result = Shard(
        data=await File.from_local(out),
        kind="agent",
        rows=len(traces),
        tokens=sum(s["tokens"] for s in stats),
        target_tokens=sum(s["target_tokens"] for s in stats),
        tool_calls=sum(s["tool_calls"] for s in stats),
        failed=len(tasks) - len(traces),
        lengths=[s["target_tokens"] for s in stats],
    )
    await flyte.report.replace.aio(data_reports.agent_shard_report(result, traces, stats))
    await flyte.report.flush.aio()
    return result
# {{/docs-fragment agent-traces}}


# {{docs-fragment build-dataset}}
@driver_env.task(report=True)
async def build_dataset(num_chat: int, num_agent: int, num_shards: int = 4) -> TrainingData:
    """Generate the full training set, every shard in parallel."""
    shards = await prepare_prompts(num_chat, num_agent, num_shards)
    with flyte.group("regenerate-chat"):
        chat = asyncio.gather(*(regenerate_chat(s) for s in shards.chat))
    with flyte.group("agent-traces"):
        agent = asyncio.gather(*(collect_agent_traces(s) for s in shards.agent))
    chat_shards, agent_shards = await asyncio.gather(chat, agent)
    data = TrainingData(chat=list(chat_shards), agent=list(agent_shards))

    await flyte.report.replace.aio(data_reports.dataset_report(data))
    await flyte.report.flush.aio()
    return data
# {{/docs-fragment build-dataset}}
